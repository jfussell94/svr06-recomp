#!/usr/bin/env python3
"""exe_regions.py - classify main-ELF functions into subsystems from string anchors, then fill gaps by neighbours.
Reads analysis/fullre/exe/mod_M*.md, writes analysis/fullre/exe/REGIONS.md and regions.json"""
import re,glob,os,json,sys
base=sys.argv[1] if len(sys.argv)>1 else 'analysis/fullre/exe'
RULES=[('CRI ADX / CVFS / DVCI file system',r'adxt_|adxf_|adxm_|ADXT|ADXF|cvFs|dvCi|DVCI|\(c\)CRI|AFS'),
('CRI Sofdec (MPEG/SFD movie)',r'mwPly|MWSFC|mwSfd|MwsfD|Mwsfd|SFD|sofdec|mpeg'),
('Network stack (eenet/gss/BSD)',r'gss|eenet|EENet|m_copy|m_pull|dhclient|soaccept|rtfree|rtrequest|icmp_|route_|raw_usrreq|looutput|netIf|Netcnf|libeenet|DHCP'),
('SCE system libs (kernel/sif/stdio/cd)',r'Sce[A-Z]|rom0:|sceSif|SceKernel'),
('GS/DMA diagnostics',r'D\d_TADR|D\d_MADR|GS_|Ver %s'),
('Game asset paths / loaders (Yukes)',r'^/?(MOT|MOTP|STG|MISC|EDIT|CHAR|CBAT|CSDT|MENU|SOUND)|/MOT|/STG|/MISC|/EDIT|/CHAR|/CBAT|/CSDT'),
('Character/skeleton data (joint names)',r'atama|koshi|sakotsu|boin|hidari|migi|ude|ashi'),
('Sound manager (Yukes)',r'snd|Snd|SOUND|sound'),
]
funcs=[]  # (addr,size,label|None)
for f in glob.glob(os.path.join(base,'mod_M*.md')):
    m=os.path.basename(f)[4:8]
    for l in open(f):
        c=[x.strip() for x in l.split('|')]
        if len(c)<8 or not re.fullmatch(r'[0-9a-f]{5,6}',c[1]): continue
        a=int(c[1],16); sz=int(c[2]); s=c[6]; lab=None
        for name,rx in RULES:
            if re.search(rx,s): lab=name;break
        cal=[int(x,16) for x in c[5].split() if re.fullmatch(r'[0-9a-f]+',x)]; cal+= [int(x,16) for x in c[4].split() if re.fullmatch(r'[0-9a-f]+',x)]
        funcs.append([a,sz,lab,m,s,cal])
MANUAL=[(0x2f6000,0x2fe000,'C library (stdio/string; vfprintf at 0x2fbce0)'),(0x1c0000,0x1d2000,'Sound manager (Yukes EE side; RPC sid 0x301)'),(0x147a98,0x147ac0,'CRI ADXF partition registrar (never runs)'),(0x156d18,0x156e00,'CRI ADXT_StartAfs (hooked)')]
for x in funcs:
    for a,b,n in MANUAL:
        if a<=x[0]<b: x[2]=n
funcs.sort()
# dedupe by addr
seen={};F=[]
for x in funcs:
    if x[0] in seen: 
        if x[2] and not seen[x[0]][2]: seen[x[0]][2]=x[2]
        continue
    seen[x[0]]=x;F.append(x)
# call-graph propagation of anchor labels (undirected, majority, 4 rounds)
import collections
byaddr={x[0]:x for x in F}
adj=collections.defaultdict(set)
for x in F:
    for y in x[5]:
        if y in byaddr: adj[x[0]].add(y);adj[y].add(x[0])
for _ in range(1):
    new={}
    for x in F:
        if x[2]: continue
        cnt=collections.Counter(byaddr[y][2] for y in adj[x[0]] if byaddr[y][2] and not byaddr[y][2].startswith('Sound manager') and 'propagated' not in byaddr[y][2])
        if cnt:
            l,n=cnt.most_common(1)[0]
            if n>=3 and n>=0.8*sum(cnt.values()): new[x[0]]=l+' (propagated)'
    for a,l in new.items(): byaddr[a][2]=l
    if not new: break
# fill gaps
lab=[x[2] for x in F]
n=len(F);prev=[None]*n;nxt=[None]*n
p=None
for i in range(n):
    prev[i]=p
    if lab[i]: p=lab[i]
p=None
for i in range(n-1,-1,-1):
    nxt[i]=p
    if lab[i]: p=lab[i]
for i in range(n):
    if not lab[i]:
        lab[i]=(prev[i]+' (inferred)') if prev[i] and prev[i]==nxt[i] else 'Unclassified (game/engine)'
# runs
runs=[];cur=None
for x,l in zip(F,lab):
    if cur and cur[0]==l: cur[2]=x[0]+x[1];cur[3]+=1;cur[4]+=x[1]
    else:
        cur=[l,x[0],x[0]+x[1],1,x[1]];runs.append(cur)
tot={}
for r in runs: t=tot.setdefault(r[0],[0,0,0]);t[0]+=r[3];t[1]+=r[4];t[2]+=1
out=['# Main ELF subsystem map (auto)','','Generated by tools/exe_regions.py from string anchors in analysis/fullre/exe/mod_*.md; gaps are filled when both neighbours agree.','','## Totals','','| subsystem | functions | bytes | runs |','|---|---:|---:|---:|']
for k,v in sorted(tot.items(),key=lambda kv:-kv[1][1]): out.append('| %s | %d | %d | %d |'%(k,v[0],v[1],v[2]))
out+=['','## Address runs (>=8 functions or >=2KB)','','| start | end | functions | bytes | subsystem |','|---|---|---:|---:|---|']
for r in runs:
    if r[3]>=8 or r[4]>=2048: out.append('| %06x | %06x | %d | %d | %s |'%(r[1],r[2],r[3],r[4],r[0]))
open(os.path.join(base,'REGIONS.md'),'w').write('\n'.join(out)+'\n')
json.dump([[hex(a) for a in (r[1],r[2])]+[r[0],r[3],r[4]] for r in runs],open(os.path.join(base,'regions.json'),'w'))
print('\n'.join(out[:20]));print(len(F),'functions,',len(runs),'runs')
