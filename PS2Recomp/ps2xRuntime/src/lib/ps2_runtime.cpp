void PS2Runtime::run()
{
    m_stopRequested.store(false, std::memory_order_relaxed);
    ps2_stubs::resetSifState();
    resetIop();
    ps2_stubs::resetAudioStubState();
    ps2_stubs::resetMpegStubState();
    initializeEeKernelState(m_memory.getRDRAM());
    svr06StartPageWatch(m_memory.getRDRAM());
    m_cpuContext.r[4] = _mm_setzero_si128();
    m_cpuContext.r[5] = _mm_setzero_si128();
    m_cpuContext.r[29] = _mm_set_epi64x(0, static_cast<int64_t>(PS2_RAM_SIZE - 0x10u));
    m_debugPc.store(m_cpuContext.pc, std::memory_order_relaxed);
    m_debugRa.store(static_cast<uint32_t>(_mm_extract_epi32(m_cpuContext.r[31], 0)), std::memory_order_relaxed);
    m_debugSp.store(static_cast<uint32_t>(_mm_extract_epi32(m_cpuContext.r[29], 0)), std::memory_order_relaxed);
    m_debugGp.store(static_cast<uint32_t>(_mm_extract_epi32(m_cpuContext.r[28], 0)), std::memory_order_relaxed);

    RUNTIME_LOG("Starting execution at address 0x" << std::hex << m_cpuContext.pc << std::dec);

    // A blank image to use as a framebuffer
    Image blank = GenImageColor(FB_WIDTH, FB_HEIGHT, BLANK);
    Texture2D frameTex = LoadTextureFromImage(blank);
    UnloadImage(blank);

    std::atomic<bool> gameThreadFinished{false};

    std::thread gameThread([&]()
                           {
        ThreadNaming::SetCurrentThreadName("GameThread");
        {
            // The EE FPU (and VU) always round toward zero. Host float ops here default to
            // round-to-nearest, which differs by one ULP in about half of the inexact results.
            // Default ON (hardware behaviour; all EE guest threads run on this one host thread). Opt out with SVR06_FPU_TRUNC=0.
            const char *trunc = std::getenv("SVR06_FPU_TRUNC");
            if (!(trunc && trunc[0] == '0'))
            {
                _mm_setcsr(_mm_getcsr() | 0x8040u); // MXCSR FTZ|DAZ: the EE FPU/VU treat denormals as zero (inputs and results)
                if (std::fesetround(FE_TOWARDZERO) == 0)
                    std::cerr << "[fpu] guest thread rounding: toward zero (default; SVR06_FPU_TRUNC=0 disables)" << std::endl;
            }
        }
        try
        {
            m_eeScheduler->reset(m_memory.getRDRAM(), m_cpuContext);
            m_eeScheduler->run();
            uint32_t pc = m_debugPc.load(std::memory_order_relaxed);
            RUNTIME_LOG("Game thread returned. PC=0x" << std::hex << pc
                      << " RA=0x" << static_cast<uint32_t>(_mm_extract_epi32(m_cpuContext.r[31], 0)) << std::dec << std::endl);
        }
        catch (const std::exception &e)
        {
            std::cerr << "Error during program execution: " << e.what() << std::endl;
        }
        catch (...)
        {
            std::cerr << "Error during program execution: unknown exception" << std::endl;
        }
        gameThreadFinished.store(true, std::memory_order_release); });

    uint64_t tick = 0;
    while (!isStopRequested() && !gameThreadFinished.load(std::memory_order_acquire))
    {
        PS2_IF_AGRESSIVE_LOGS({
            tick++;
            if ((tick % 120) == 0)
            {
                uint64_t curDma = m_memory.dmaStartCount();
                uint64_t curGif = m_memory.gifCopyCount();
                uint64_t curGs = m_memory.gsWriteCount();
                uint64_t curVif = m_memory.vifWriteCount();
                const GSRegisters &gs = m_memory.gs();
                const uint32_t dbgPc = m_debugPc.load(std::memory_order_relaxed);
                const uint32_t dbgRa = m_debugRa.load(std::memory_order_relaxed);
                const uint32_t dbgSp = m_debugSp.load(std::memory_order_relaxed);
                const uint32_t dbgGp = m_debugGp.load(std::memory_order_relaxed);
                const auto eeSnapshot = m_eeScheduler->snapshot();

                RUNTIME_LOG("[run:tick] tick=" << tick
                                               << " pc=0x" << std::hex << dbgPc
                                               << " ra=0x" << dbgRa
                                               << " sp=0x" << dbgSp
                                               << " gp=0x" << dbgGp
                                               << " dispfb1=0x" << gs.dispfb1
                                               << " display1=0x" << gs.display1
                                               << std::dec
                                               << " activeThreads=" << eeSnapshot.threads.size()
                                               << " dma=" << curDma
                                               << " gif=" << curGif
                                               << " gsw=" << curGs
                                               << " vif=" << curVif
                                               << std::endl);

            }
        });
        uint32_t presentWidth = FB_WIDTH;
        uint32_t presentHeight = DEFAULT_DISPLAY_HEIGHT;
        UploadFrame(frameTex, this, presentWidth, presentHeight);

        BeginDrawing();
        ClearBackground(BLACK);
        const float srcWidth = static_cast<float>(std::max<uint32_t>(1u, presentWidth));
        const float srcHeight = static_cast<float>(std::max<uint32_t>(1u, presentHeight));
        const float screenWidth = static_cast<float>(GetScreenWidth());
        const float screenHeight = static_cast<float>(GetScreenHeight());
        // Present at the TV aspect (default 4:3) instead of the raw buffer aspect (e.g. 640x256 field buffers).
        // SVR06_ASPECT: "4:3" (default), "16:9", "21:9", "stretch", "raw".
        float aspect = 4.0f / 3.0f;
        {
            const int sa = ps2settings::getInt("graphics.aspect", 0);
            if (sa == 1) aspect = 16.0f / 9.0f; else if (sa == 2) aspect = 64.0f / 27.0f; else if (sa == 3) aspect = screenWidth / std::max(1.0f, screenHeight);
        }
        {
            static const char *s_aspect = std::getenv("SVR06_ASPECT");
            if (s_aspect)
            {
                const std::string a = s_aspect;
                if (a == "16:9") aspect = 16.0f / 9.0f;
                else if (a == "21:9") aspect = 64.0f / 27.0f;
                else if (a == "stretch") aspect = screenWidth / std::max(1.0f, screenHeight);
                else if (a == "raw") aspect = srcWidth / srcHeight;
            }
        }
        float dstWidth = screenWidth;
        float dstHeight = screenWidth / aspect;
        if (dstHeight > screenHeight) { dstHeight = screenHeight; dstWidth = screenHeight * aspect; }
        const Rectangle srcRect{0.0f, 0.0f, srcWidth, srcHeight};
        const Rectangle dstRect{
            (screenWidth - dstWidth) * 0.5f,
            (screenHeight - dstHeight) * 0.5f,
            dstWidth,
            dstHeight};
        { extern std::function<std::string()> g_svr06ThreadDumpFn; static bool s_tdReg = false;
          if (!s_tdReg) { s_tdReg = true; g_svr06ThreadDumpFn = [this]() -> std::string {
              std::string r; if (!m_eeScheduler) return "no scheduler\n";
              const auto sn = m_eeScheduler->snapshot(); char b[200];
              std::snprintf(b, sizeof b, "running=%d vsync=%llu\n", (int)sn.runningThreadId, (unsigned long long)m_eeScheduler->currentVSyncTick()); r += b;
              for (const auto &t : sn.threads) { std::snprintf(b, sizeof b, "th%d st=%d pc=%08X ra=%08X entry=%08X prio=%d wr=%d wid=%d susp=%d wake=%u\n", (int)t.id, (int)t.status, (unsigned)t.pc, (unsigned)t.ra, (unsigned)t.entry, (int)t.currentPriority, (int)t.waitReason, (int)t.waitId, (int)t.suspendCount, (unsigned)t.wakeupCount); r += b; }
              return r; }; } }
        { extern void svr06_console_poll(uint8_t *); svr06_console_poll(m_memory.getRDRAM()); }
        {
            static int s_kd = 0;
            if ((++s_kd % 120) == 0)
            {
                const char *rq = "analysis/live/threads.req";
                std::error_code kec;
                if (std::filesystem::exists(rq, kec))
                {
                    std::filesystem::remove(rq, kec);
                    const EeKernelSnapshot ks = eeScheduler().snapshot();
                    FILE *kf = std::fopen("analysis/live/threads.txt", "w");
                    if (kf)
                    {
                        std::fprintf(kf, "running=%d seq=%llu\n", ks.runningThreadId, (unsigned long long)ks.sequence);
                        for (const auto &t : ks.threads)
                            std::fprintf(kf, "T%d pc=%X ra=%X entry=%X prio=%d st=%d wr=%d wid=%d susp=%d wake=%u\n", t.id, t.pc, t.ra, t.entry, t.currentPriority, (int)t.status, (int)t.waitReason, t.waitId, t.suspendCount, t.wakeupCount);
                        for (const auto &sm : ks.semaphores)
                            std::fprintf(kf, "S%d count=%d max=%d waiters=%u\n", sm.id, sm.count, sm.maxCount, sm.waiters);
                        for (const auto &e : ks.eventFlags)
                            std::fprintf(kf, "E%d bits=%X waiters=%u\n", e.id, e.bits, e.waiters);
                        std::fclose(kf);
                    }
                }
            }
        }
        extern void svr06_adjust_begin(int, int); extern void svr06_adjust_end();
        svr06_adjust_begin(static_cast<int>(srcWidth), static_cast<int>(srcHeight));
        if (!svr06_movie_present(dstRect.x, dstRect.y, dstRect.width, dstRect.height))
            DrawTexturePro(frameTex, srcRect, dstRect, Vector2{0.0f, 0.0f}, 0.0f, WHITE);
        else
        {
            // movie playing natively: lay the game's own picture (PRESS START pill bar, glyphs, subtitles) OVER the movie.
            // CL-0111 / ISS-104: the old additive blend dropped every UI pixel whose framebuffer alpha was 0 (the pill bar), and
            // could never make a UI element opaque. The game's frame is black wherever the PS2 showed the video, so a luminance key
            // (alpha from max(r,g,b)) shows the UI opaquely and lets the movie through elsewhere, as on hardware.
            static Shader s_key{}; static int s_keyState = 0; // 0 untried, 1 ok, -1 failed
            if (s_keyState == 0)
            {
                static const char *kFs =
                    "#version 330\n"
                    "in vec2 fragTexCoord; in vec4 fragColor; uniform sampler2D texture0; out vec4 finalColor;\n"
                    "void main(){ vec3 c = texture(texture0, fragTexCoord).rgb; float m = max(c.r, max(c.g, c.b));\n"
                    "  finalColor = vec4(c, smoothstep(0.015, 0.09, m)); }\n";
                s_key = LoadShaderFromMemory(nullptr, kFs);
                s_keyState = (s_key.id != 0 && s_key.id != rlGetShaderIdDefault()) ? 1 : -1;
                std::fprintf(stderr, "[moviekey] luma-key shader %s\n", s_keyState == 1 ? "ok" : "FAILED (additive fallback)");
            }
            if (s_keyState == 1)
            {
                BeginShaderMode(s_key);
                DrawTexturePro(frameTex, srcRect, dstRect, Vector2{0.0f, 0.0f}, 0.0f, WHITE);
                EndShaderMode();
            }
            else
            {
                BeginBlendMode(BLEND_ADDITIVE);
                DrawTexturePro(frameTex, srcRect, dstRect, Vector2{0.0f, 0.0f}, 0.0f, WHITE);
                EndBlendMode();
            }
        }
        svr06_adjust_end();
        {
            // settings: fullscreen (F11 / menu) and texture filter, applied live
            static int s_filt = -1;
            if (IsKeyPressed(KEY_F11)) ps2settings::set("graphics.fullscreen", ps2settings::getInt("graphics.fullscreen", 0) ? 0 : 1);
            const bool wantFs = ps2settings::getInt("graphics.fullscreen", 0) != 0;
            if (wantFs != IsWindowFullscreen()) ToggleFullscreen();
            const int wantFilt = ps2settings::getInt("graphics.filter", 0);
            if (wantFilt != s_filt) { SetTextureFilter(frameTex, wantFilt ? TEXTURE_FILTER_BILINEAR : TEXTURE_FILTER_POINT); s_filt = wantFilt; }
        }
        {
            // SvR06: FPS counter (F3 toggles). Counts presented frames per second.
            static bool s_showFps = true; (void)s_showFps;
            static double s_t0 = GetTime(); static int s_frames = 0; static int s_fps = 0;
            if (IsKeyPressed(KEY_F3)) ps2settings::set("graphics.showFps", ps2settings::getInt("graphics.showFps", 1) ? 0 : 1);
            ++s_frames;
            const double now = GetTime();
            if (now - s_t0 >= 0.5) { s_fps = static_cast<int>(s_frames / (now - s_t0) + 0.5); s_frames = 0; s_t0 = now; }
            if (ps2settings::getInt("graphics.showFps", 1))
            {
                // run clock + frame counters: lets screenshots and logs be matched to the moment a bug happens (see the [shot]/[clock] log lines)
                static const double s_runT0 = GetTime(); static uint64_t s_presented = 0; ++s_presented;
                const int runSec = static_cast<int>(GetTime() - s_runT0);
                char buf[96]; std::snprintf(buf, sizeof buf, "%d FPS  %02d:%02d  f%llu  v%llu", s_fps, runSec / 60, runSec % 60,
                                            static_cast<unsigned long long>(s_presented), static_cast<unsigned long long>(eeScheduler().currentVSyncTick()));
                DrawText(buf, 11, 11, 20, BLACK);
                DrawText(buf, 10, 10, 20, s_fps >= 55 ? GREEN : (s_fps >= 40 ? YELLOW : RED));
            }
        }
        { extern void svr06_music_popup_draw(int, int); svr06_music_popup_draw(GetScreenWidth(), GetScreenHeight()); } // [custommusic] CL-0118 now-playing popup
        {
            // [SVR06 menu] Ship-of-Harkinian style menu (ps2_ship_menu.cpp)
            extern void svr06_menu_frame();
            svr06_menu_frame();
        }
        if (m_debugUiInitialized && m_debugUiDrawCallback)
        {
            m_debugUiDrawCallback(*this, m_debugUiUserData);
        }
        EndDrawing();

        if (WindowShouldClose())
        {
            RUNTIME_LOG("[run] window close requested, breaking out of loop");
            requestStop();
            break;
        }
    }

    requestStop();
    if (gameThread.joinable())
    {
        gameThread.join();
    }

    if (m_debugUiInitialized && m_debugUiShutdownCallback)
    {
        m_debugUiShutdownCallback(*this, m_debugUiUserData);
        m_debugUiInitialized = false;
    }
    UnloadTexture(frameTex);
    CloseWindow();

    RUNTIME_LOG("[run] exiting loop");
}
