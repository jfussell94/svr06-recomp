bool svr06_movie_present(float,float,float,float);
bool svr06_movie_active(); bool svr06_movie_holding();
static void UploadFrame(Texture2D &tex, PS2Runtime *rt, uint32_t &outWidth, uint32_t &outHeight)
{
    static uint64_t s_lastPresentationTick = std::numeric_limits<uint64_t>::max();
    static bool s_hasLatchedInitialFrame = false;
    static uint32_t s_lastDisplayFbp = std::numeric_limits<uint32_t>::max();
    static uint32_t s_lastSourceFbp = std::numeric_limits<uint32_t>::max();
    static bool s_lastPreferred = false;
    static uint32_t s_lastWidth = 0u;
    static uint32_t s_lastHeight = 0u;
    static bool s_hasUploadedFrame = false;
    static std::vector<uint8_t> s_scratch;
    static std::vector<uint8_t> s_uploadBuffer(DEFAULT_FB_SIZE, 0u);

    const uint64_t currentTick = rt->eeScheduler().currentVSyncTick();
    const bool needsLatch = !s_hasLatchedInitialFrame || currentTick != s_lastPresentationTick;
    if (needsLatch)
    {
        // Wait (bounded) for the CPU rasterizer to go quiet so we don't latch a half-drawn frame.
        {
            const auto nowNs = []() { return std::chrono::duration_cast<std::chrono::nanoseconds>(std::chrono::steady_clock::now().time_since_epoch()).count(); };
            // CL-0112: while a native movie plays (logos, brand video, title), never block the presenter: the movie runs on
            // its own clock and the game layer is only static UI. If the GS is busy, keep showing the last game layer and
            // retry next present, so intros/movies hold a steady 60 FPS instead of 40-48 (the 40 ms wait below).
            static int s_movieSkips = 0; // after 6 skipped latches in a row fall through to the normal wait so the UI layer can never freeze
            if (s_hasUploadedFrame && s_movieSkips < 6 && (svr06_movie_active() || svr06_movie_holding()) &&
                (nowNs() - g_svr06LastDrawNs.load() < 4000000LL || !svr06MtgsIdle()))
            {
                ++s_movieSkips;
                outWidth = (s_lastWidth != 0u) ? s_lastWidth : FB_WIDTH;
                outHeight = (s_lastHeight != 0u) ? s_lastHeight : DEFAULT_DISPLAY_HEIGHT;
                return;
            }
            s_movieSkips = 0;
            const int64_t waitCap = (svr06_movie_active() || svr06_movie_holding()) ? 6000000LL : 40000000LL; // movies: never miss a 60 Hz present
            const int64_t start = nowNs();
            while (nowNs() - start < waitCap && (nowNs() - g_svr06LastDrawNs.load() < 4000000LL || !svr06MtgsIdle()))
                std::this_thread::sleep_for(std::chrono::microseconds(500));
        }
        rt->gs().latchHostPresentationFrame();
        s_lastPresentationTick = currentTick;
        s_hasLatchedInitialFrame = true;
    }
    else if (s_hasUploadedFrame)
    {
        outWidth = (s_lastWidth != 0u) ? s_lastWidth : FB_WIDTH;
        outHeight = (s_lastHeight != 0u) ? s_lastHeight : DEFAULT_DISPLAY_HEIGHT;
        return;
    }

    s_scratch.clear();
    uint32_t width = 0u;
    uint32_t height = 0u;
    uint32_t displayFbp = 0u;
    uint32_t sourceFbp = 0u;
    bool usedPreferredDisplaySource = false;
    if (!rt->gs().copyLatchedHostPresentationFrame(s_scratch,
                                                   width,
                                                   height,
                                                   &displayFbp,
                                                   &sourceFbp,
                                                   &usedPreferredDisplaySource))
    {
        Image blank = GenImageColor(FB_WIDTH, FB_HEIGHT, MAGENTA);
        UpdateTexture(tex, blank.data);
        UnloadImage(blank);
        outWidth = FB_WIDTH;
        outHeight = DEFAULT_DISPLAY_HEIGHT;
        s_lastWidth = outWidth;
        s_lastHeight = outHeight;
        s_hasUploadedFrame = true;
        return;
    }

    PS2_IF_AGRESSIVE_LOGS({
        static uint32_t s_uploadDebugCount = 0u;
        if (s_uploadDebugCount < 128u ||
            displayFbp != s_lastDisplayFbp ||
            sourceFbp != s_lastSourceFbp ||
            usedPreferredDisplaySource != s_lastPreferred ||
            width != s_lastWidth ||
            height != s_lastHeight)
        {
            std::cout << "[frame:upload] idx=" << s_uploadDebugCount
                      << " tick=" << currentTick
                      << " displayFbp=" << displayFbp
                      << " sourceFbp=" << sourceFbp
                      << " size=" << width << "x" << height
                      << " preferred=" << static_cast<uint32_t>(usedPreferredDisplaySource ? 1u : 0u)
                      << std::endl;
        }
        ++s_uploadDebugCount;
    });
    s_lastDisplayFbp = displayFbp;
    s_lastSourceFbp = sourceFbp;
    s_lastPreferred = usedPreferredDisplaySource;
    s_lastWidth = width;
    s_lastHeight = height;

    std::fill(s_uploadBuffer.begin(), s_uploadBuffer.end(), 0u);
    if (!s_scratch.empty() && width != 0u && height != 0u)
    {
        const uint32_t copyWidth = std::min<uint32_t>(width, FB_WIDTH);
        const uint32_t copyHeight = std::min<uint32_t>(height, FB_HEIGHT);
        const size_t srcRowBytes = static_cast<size_t>(width) * 4u;
        const size_t dstRowBytes = static_cast<size_t>(FB_WIDTH) * 4u;
        const size_t copyRowBytes = static_cast<size_t>(copyWidth) * 4u;
        for (uint32_t y = 0; y < copyHeight; ++y)
        {
            const size_t srcOffset = static_cast<size_t>(y) * srcRowBytes;
            const size_t dstOffset = static_cast<size_t>(y) * dstRowBytes;
            if (srcOffset + copyRowBytes > s_scratch.size() ||
                dstOffset + copyRowBytes > s_uploadBuffer.size())
            {
                break;
            }
            std::memcpy(s_uploadBuffer.data() + dstOffset, s_scratch.data() + srcOffset, copyRowBytes);
        }
    }

    UpdateTexture(tex, s_uploadBuffer.data());
    {
        // SvR06: cheap brightness estimate of the game's frame (drives the held title picture's fade)
        extern std::atomic<float> g_svr06FrameLum;
        const size_t n = s_uploadBuffer.size() / 4; uint64_t sum = 0; size_t cnt = 0;
        for (size_t i = 0; i < n; i += 97) { const uint8_t *px = s_uploadBuffer.data() + i * 4; sum += std::max(px[0], std::max(px[1], px[2])); ++cnt; }
        g_svr06FrameLum.store(cnt ? static_cast<float>(sum) / static_cast<float>(cnt) : 0.0f);
    }
    {
        static int s_shotN = 0; static int s_frames = 0;
        const char *shotDir = std::getenv("SVR06_SHOTDIR");
        if (shotDir) { const char *df = std::getenv("SVR06_DUMPFRAME"); if (df && (s_frames + 1) == static_cast<size_t>(std::atoi(df)))
        { const std::string dfn = std::string(shotDir) + "/../dumps/ram_frame.bin"; if (FILE *dff = std::fopen(dfn.c_str(), "wb")) { std::fwrite(rt->memory().getRDRAM(), 1, PS2_RAM_SIZE, dff); std::fclose(dff); std::cout << "[dump] ram_frame.bin written" << std::endl; } } }
        if (shotDir && (++s_frames % 240) == 0 && s_shotN < 600)
        {
            size_t lit = 0; const size_t n = s_uploadBuffer.size() / 4;
            for (size_t i = 0; i < n; i += 7) { const uint8_t *px = s_uploadBuffer.data() + i * 4; if (px[0] | px[1] | px[2]) ++lit; }
            static const auto s_shotT0 = std::chrono::steady_clock::now();
            const double runSecs = std::chrono::duration<double>(std::chrono::steady_clock::now() - s_shotT0).count();
            std::cout << "[shot] frame=" << s_frames << " t=" << static_cast<int>(runSecs / 60) << ":" << (static_cast<int>(runSecs) % 60 < 10 ? "0" : "") << (static_cast<int>(runSecs) % 60)
                      << " vsync=" << currentTick << " litSamples=" << lit << " of " << (n / 7) << std::endl;
            static std::vector<uint8_t> s_shotBuf; const uint32_t sw = std::max<uint32_t>(1u, std::min<uint32_t>(width, FB_WIDTH)), sh = std::max<uint32_t>(1u, std::min<uint32_t>(height, FB_HEIGHT));
            s_shotBuf.assign(static_cast<size_t>(sw) * sh * 4u, 0u);
            for (uint32_t yy = 0; yy < sh; ++yy) { std::memcpy(s_shotBuf.data() + static_cast<size_t>(yy) * sw * 4u, s_uploadBuffer.data() + static_cast<size_t>(yy) * FB_WIDTH * 4u, sw * 4u); for (uint32_t xx = 0; xx < sw; ++xx) s_shotBuf[(static_cast<size_t>(yy) * sw + xx) * 4u + 3u] = 255u; }
            Image img{}; img.data = s_shotBuf.data(); img.width = static_cast<int>(sw); img.height = static_cast<int>(sh);
            img.mipmaps = 1; img.format = PIXELFORMAT_UNCOMPRESSED_R8G8B8A8;
            const std::string fn = std::string(shotDir) + "/shot_" + std::to_string(s_shotN++) + ".png";
            ExportImage(img, fn.c_str());
        }
    }
    outWidth = width;
    outHeight = height;
    s_hasUploadedFrame = true;
}

PS2Runtime::PS2Runtime()
{
    m_iopHost = std::make_unique<PS2IopHostAdapter>(*this);
    m_iopSubsystem = std::make_unique<ps2x::iop::IopSubsystem>(*m_iopHost);

    m_eeScheduler = std::make_unique<EeScheduler>(*this);

    // Assign rather than memset: R5900Context's constructor zeroes itself and
    // then applies the COP0 reset values, which a memset here would discard.
    m_cpuContext = R5900Context{};

    // R0 is always zero in MIPS
    m_cpuContext.r[0] = _mm_set1_epi32(0);
    m_cpuContext.vu0_vf[0] = _mm_set_ps(1.0f, 0.0f, 0.0f, 0.0f);
    m_cpuContext.vu0_q = 1.0f;
    m_cpuContext.vu0_r = _mm_castsi128_ps(_mm_set1_epi32(0x3F800000));

    // Stack pointer (SP) and global pointer (GP) will be set by the loaded ELF

    m_loadedModules.clear();
    m_guestHeapBlocks.clear();
    m_guestHeapBase = kGuestHeapDefaultBase;
    m_guestHeapEnd = kGuestHeapDefaultBase;
    m_guestHeapLimit = std::min(kGuestHeapHardLimit, PS2_RAM_SIZE);
    m_guestHeapSuggestedBase = kGuestHeapDefaultBase;
    m_guestHeapConfigured = false;
    m_asyncCallbackStackFloor = std::min(kGuestHeapHardLimit, PS2_RAM_SIZE);
    m_asyncCallbackStackTop = 0x01FF0000u;
}

